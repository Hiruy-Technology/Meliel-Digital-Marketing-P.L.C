/** The same shape as `en`, but any wording: am.ts must fill every key, or the build fails. */
type Wording<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? readonly Wording<U>[]
    : { [K in keyof T]: Wording<T[K]> };

export type Dictionary = Wording<typeof en>;
