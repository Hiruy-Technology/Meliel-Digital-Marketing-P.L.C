// Builds docs/06-amharic-review.md: every English string beside its Amharic draft, for Jacob's review
// and Meliel's sign-off. Fails if an Amharic string is missing, has no Amharic in it, or lost a {slot}.
// Run after any wording change: pnpm amharic

import { registerHooks } from "node:module";
import { pathToFileURL } from "node:url";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

// Node runs the .ts files directly; this only teaches it the project's "@/" import alias.
registerHooks({
  resolve(specifier, context, next) {
    if (specifier.startsWith("@/")) {
      const file = `${root}src/${specifier.slice(2)}.ts`;
      return { url: pathToFileURL(file).href, shortCircuit: true };
    }
    return next(specifier, context);
  },
});

const { en } = await import(pathToFileURL(`${root}src/i18n/en.ts`).href);
const { am } = await import(pathToFileURL(`${root}src/i18n/am.ts`).href);
const { services } = await import(
  pathToFileURL(`${root}src/content/seed.ts`).href
);
const { servicesAm } = await import(
  pathToFileURL(`${root}src/content/services-am.ts`).href
);
const profile = await import(
  pathToFileURL(`${root}src/content/profile.ts`).href
);

// Fine to stay in Latin letters: brand names used as labels.
const LATIN_OK = new Set(["WhatsApp", "Telegram"]);
// Meliel's own Amharic is laid out differently from the English (see am.ts), so it has its own table.
const SKIP = new Set(["copy.nameMeaning"]);

const problems = [];
const rows = new Map();

function add(section, key, english, amharic) {
  const slots = (s) => (s.match(/\{\w+\}/g) ?? []).sort().join();
  if (typeof amharic !== "string" || amharic.trim() === "") {
    problems.push(`${key}: missing`);
  } else {
    if (!/[ሀ-፿]/.test(amharic) && !LATIN_OK.has(amharic)) {
      problems.push(`${key}: no Amharic in it`);
    }
    if (slots(english) !== slots(amharic)) {
      problems.push(`${key}: slots differ from the English`);
    }
  }
  if (!rows.has(section)) rows.set(section, []);
  rows.get(section).push([key, english, amharic]);
}

function walk(a, b, path, section) {
  if (SKIP.has(path)) return;
  if (typeof a === "string") return add(section, path, a, b);
  if (Array.isArray(a) && a.length !== b?.length) {
    problems.push(`${path}: ${a.length} items in English, ${b?.length} here`);
  }
  for (const key of Object.keys(a)) {
    walk(a[key], b?.[key], `${path}.${key}`, section);
  }
}

for (const section of Object.keys(en)) {
  walk(en[section], am[section], section, section);
}

for (const service of services) {
  const draft = servicesAm[service.slug];
  const section = "services (data)";
  const key = `service.${service.slug}`;
  add(section, `${key}.name`, service.name, draft?.name);
  add(section, `${key}.summary`, service.summary, draft?.summary);
  if (service.note) add(section, `${key}.note`, service.note, draft?.note);
  if (service.includes.length !== draft?.includes.length) {
    problems.push(`${key}: includes lists differ in length`);
  }
  service.includes.forEach((item, i) =>
    add(section, `${key}.includes.${i}`, item, draft?.includes[i]),
  );
}

// The company profile: sectors, team roles and case-study results (client and personal names stay as written).
const p = "company profile (data)";
add(p, "contact.address", profile.contact.address, profile.contact.addressAm);
for (const s of profile.sectors) add(p, `sector.${s.slug}`, s.name, s.nameAm);
for (const m of profile.team) add(p, `team.${m.name}`, m.role, m.roleAm);
for (const c of profile.caseStudies) {
  c.highlights.forEach((h, i) =>
    add(
      p,
      `${c.slug}.highlight.${i}`,
      `${h.value} ${h.label}`,
      `${h.value} ${h.labelAm}`,
    ),
  );
  if (c.results.length !== c.resultsAm.length)
    problems.push(`${c.slug}: results and resultsAm differ in length`);
  c.results.forEach((line, i) =>
    add(p, `${c.slug}.result.${i}`, line, c.resultsAm[i]),
  );
}

if (problems.length > 0) {
  console.error(`${problems.length} problem(s):\n  ${problems.join("\n  ")}`);
  process.exit(1);
}

const cell = (text) => String(text).replace(/\|/g, "\\|");
const total = [...rows.values()].reduce((n, list) => n + list.length, 0);

const doc = [
  "# Amharic review",
  "",
  "Generated by `pnpm amharic`. Don't edit this file: change `src/i18n/am.ts` or `src/content/services-am.ts`, then regenerate.",
  "",
  `**Status: draft.** ${total} strings, drafted by Claude. Jacob reviews, Meliel signs off, then \`amharicApproved\` in \`src/i18n/config.ts\` is switched on.`,
  "",
  "## Meliel's own Amharic",
  "",
  "This text is Meliel's and is used word for word, so it needs no translation review. On `/am/about` it replaces the English column, split into the same layout:",
  "",
  ...am.copy.nameMeaning.english.paragraphs.map((p) => `- ${p}`),
  "",
  ...[...rows].flatMap(([section, list]) => [
    `## ${section}`,
    "",
    "| Key | English | Amharic draft |",
    "|---|---|---|",
    ...list.map(([key, a, b]) => `| \`${key}\` | ${cell(a)} | ${cell(b)} |`),
    "",
  ]),
].join("\n");

writeFileSync(`${root}docs/06-amharic-review.md`, doc);
console.log(`${total} strings checked. Wrote docs/06-amharic-review.md`);
